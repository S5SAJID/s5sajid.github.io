// Generates src/lucideIconNames.generated.ts — an exact PascalCase → kebab-case
// map for the lucide-react icon set. Lucide's kebab names are curated (e.g.
// "grid-2x2" vs "calendar-x-2"), so they cannot be derived mechanically; the
// canonical mapping comes from lucide's own icons/index.mjs re-export table.
//
// Run after bumping lucide-react:  bun run scripts/generate-lucide-icon-names.mjs

import {readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
const indexPath = require.resolve('lucide-react/dist/esm/icons/index.mjs');
const indexSource = readFileSync(indexPath, 'utf8');

const EXPORT_PATTERN =
  /^export \{ default as ([A-Za-z0-9]+) \} from '\.\/([a-z0-9-]+)\.mjs';$/gm;

const entries = [];
for (const [, pascalName, kebabName] of indexSource.matchAll(EXPORT_PATTERN)) {
  entries.push(`  ${JSON.stringify(pascalName)}: ${JSON.stringify(kebabName)},`);
}

const output = `// Generated by scripts/generate-lucide-icon-names.mjs — do not edit.
// Maps lucide-react PascalCase exports to their canonical kebab-case names.

export const lucideIconNameByPascalCase: Record<string, string> = {
${entries.join('\n')}
};
`;

writeFileSync(
  new URL('../src/lucideIconNames.generated.ts', import.meta.url),
  output,
);
console.log(`Generated map with ${entries.length} icons.`);
